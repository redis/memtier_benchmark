static int failures = 0;
#define CHECK(condition)                                                                                               \
    do {                                                                                                               \
        if (!(condition)) {                                                                                            \
            fprintf(stderr, "FAIL line %d: %s\n", __LINE__, #condition);                                               \
            failures++;                                                                                                \
        }                                                                                                              \
    } while (0)

static hdr_histogram *new_histogram()
{
    hdr_histogram *h = NULL;
    if (hdr_init(10, 600000000LL, 2, &h) != 0) abort();
    return h;
}

static void compare_histograms(const hdr_histogram *a, const hdr_histogram *b)
{
    CHECK(a->counts_len == b->counts_len);
    CHECK(hdr_total_count(a) == hdr_total_count(b));
    for (int i = 0; i < a->counts_len; ++i) {
        const int64_t value = hdr_value_at_index(a, i);
        CHECK(hdr_count_at_value(a, value) == hdr_count_at_value(b, value));
    }
    const double percentiles[] = {0, 50, 95, 99, 99.9, 100};
    for (double p : percentiles)
        CHECK(hdr_value_at_percentile(a, p) == hdr_value_at_percentile(b, p));
}

static void test_clamping()
{
    hdr_histogram *plain = new_histogram();
    hdr_histogram *atomic = new_histogram();
    hdr_histogram *expected = new_histogram();
    const int64_t inputs[] = {INT64_MIN, -1, 0, 1, 9, 10, 11, 1000, 599999999, 600000000, 700000000, INT64_MAX};
    const int64_t clamped[] = {10, 10, 10, 10, 10, 10, 11, 1000, 599999999, 600000000, 600000000, 600000000};
    for (size_t i = 0; i < sizeof(inputs) / sizeof(inputs[0]); ++i) {
        CHECK(memtier_record_latency(plain, inputs[i]));
        CHECK(memtier_record_latency_atomic(atomic, inputs[i]));
        CHECK(hdr_record_value(expected, clamped[i]));
    }
    compare_histograms(plain, expected);
    compare_histograms(atomic, expected);
    CHECK(hdr_count_at_value(plain, 0) == 0);
    CHECK(hdr_total_count(NULL) == 0);
    hdr_close(plain);
    hdr_close(atomic);
    hdr_close(expected);
}

static void test_atomic_recording()
{
    hdr_histogram *h = new_histogram();
    std::vector<std::thread> writers;
    for (int t = 0; t < 4; ++t) {
        writers.emplace_back([h]() {
            for (int i = 0; i < 10000; ++i) {
                // Fail immediately without racing the test's failure counter.
                if (!memtier_record_latency_atomic(h, i % 2 ? 0 : 700000000)) abort();
            }
        });
    }
    for (std::thread &writer : writers)
        writer.join();
    CHECK(hdr_total_count(h) == 40000);
    CHECK(hdr_count_at_value(h, 10) == 20000);
    CHECK(hdr_count_at_value(h, 600000000) == 20000);
    hdr_close(h);
}

static void test_codec_and_percentiles()
{
    // Generated by the previously vendored library at memtier 2ed605f, using
    // hdr_init(10, 600000000, 2) and hdr_record_value_capped for these inputs.
    char legacy[] = "HISTFAAAAC14nJNpmSzMwMDAywABTFCaC0QoH3ZjsP8AEWDkEma6z8j0WphpsxALAIsHBoY=";
    const int64_t inputs[] = {0, 1, 9, 10, 11, 100, 1000, 1000000, 600000000, 700000000};
    hdr_histogram *expected = new_histogram();
    for (int64_t v : inputs)
        CHECK(memtier_record_latency(expected, v));
    hdr_histogram *decoded = NULL;
    int rc = hdr_log_decode(&decoded, legacy, strlen(legacy));
    CHECK(rc == 0);
    if (rc == 0) compare_histograms(expected, decoded);
    hdr_close(decoded);

    char *encoded = NULL;
    rc = hdr_log_encode(expected, &encoded);
    CHECK(rc == 0);
    decoded = NULL;
    if (rc == 0) {
        rc = hdr_log_decode(&decoded, encoded, strlen(encoded));
        CHECK(rc == 0);
        if (rc == 0) compare_histograms(expected, decoded);
    }
    free(encoded);
    hdr_close(decoded);

    const double percentiles[] = {50, 95, 99, 99.9, 100};
    int64_t values[5];
    CHECK(hdr_value_at_percentiles(expected, percentiles, values, 5) == 0);
    for (size_t i = 0; i < 5; ++i)
        CHECK(values[i] == hdr_value_at_percentile(expected, percentiles[i]));
    CHECK(!hdr_record_values(expected, 100, -1));
    CHECK(hdr_total_count(expected) == 10);
    hdr_reset(expected);
    CHECK(hdr_value_at_percentiles(expected, percentiles, values, 5) == 0);
    // Both the previous vendored batch implementation and 0.12.0 leave the
    // rank-one placeholders for an empty histogram; preserve that API behavior.
    for (int64_t value : values)
        CHECK(value == 1);
    hdr_close(expected);
}

static void test_batched_scalar_compatibility()
{
    hdr_histogram *h = new_histogram();
    const std::vector<double> quantiles = {100, 0, 99.999999, 50, 99, 50, 0, 0.001, 99.9};
    latency_percentiles query(quantiles);
    const int64_t *storage = query.values().data();
    for (int population = 0; population < 4; ++population) {
        hdr_reset(h);
        if (population == 1) CHECK(memtier_record_latency(h, 10));
        if (population == 2) {
            CHECK(hdr_record_values(h, 10, 999));
            CHECK(hdr_record_values(h, 600000000, 1));
        }
        if (population == 3) {
            for (int i = 0; i < h->counts_len; ++i) {
                const int64_t value = hdr_value_at_index(h, i);
                if (value <= h->highest_trackable_value) CHECK(hdr_record_values(h, value, 1 + (i * 17) % 101));
            }
        }
        const int64_t count = hdr_total_count(h);
        for (int repeat = 0; repeat < 3; ++repeat) {
            const std::vector<int64_t> &values = query.calculate(h);
            CHECK(values.data() == storage);
            CHECK(values.size() == quantiles.size());
            for (size_t i = 0; i < quantiles.size(); ++i)
                CHECK(values[i] == hdr_value_at_percentile(h, quantiles[i]));
            CHECK(hdr_total_count(h) == count);
        }
    }
    latency_percentiles none(std::vector<double>{});
    CHECK(none.calculate(h).empty());
    hdr_close(h);
}

static void test_summary_scratch_reuse()
{
    safe_hdr_histogram h;
    one_sec_cmd_stats stats;
    const std::vector<double> quantiles = {0, 50, 99.9, 100};
    std::vector<int64_t> scratch;
    for (int tick = 0; tick < 3; ++tick) {
        hdr_reset(h);
        stats.reset();
        if (tick != 1) CHECK(memtier_record_latency(h, 10 + tick * 10000));
        int64_t expected[4];
        CHECK(hdr_value_at_percentiles(h, quantiles.data(), expected, 4) == 0);
        stats.summarize_quantiles(h, quantiles, scratch);
        CHECK(stats.summarized_quantile_values.size() == 4);
        for (size_t i = 0; i < 4; ++i)
            CHECK(stats.summarized_quantile_values[i] == expected[i] / 1000.0);
        const int64_t *storage = scratch.data();
        stats.reset();
        stats.summarize_quantiles(h, quantiles, scratch);
        CHECK(scratch.data() == storage);
    }
    stats.reset();
    stats.summarize_quantiles(h, std::vector<double>{}, scratch);
    CHECK(stats.summarized_quantile_values.empty());
}

int main()
{
    test_clamping();
    test_atomic_recording();
    test_codec_and_percentiles();
    test_batched_scalar_compatibility();
    test_summary_scratch_reuse();
    if (failures) fprintf(stderr, "%d HDR compatibility checks failed\n", failures);
    return failures ? 1 : 0;
}
